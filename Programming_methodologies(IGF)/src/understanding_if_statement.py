# if Statement
cars = ["audi", 'bmw', "subaru", 'toyota']
for car in cars:
    if car == 'audi':
        print(car.upper())
    else:
        print(car)


# El condicional o condution
# El condicional es el corazon del if

# Condicional Verdadero
# Condicional True
truck = "ford"
print(truck == 'ford')

# Condicional Falso
# Conditional False
print(truck == 'audi')

#
print(truck == 'Ford'.lower())


# Condicional de desigualdad !=
print(truck!="audi") # True
print(truck!="ford") # False


